//! Renders a root `README.md` with client environment setup instructions and
//! a route index for all generated `.http` files.

use std::collections::BTreeSet;
use std::fmt::Write as _;

use forge::Forge;

use super::HttpFile;
use super::synth::normalize_lf;

/// Summary of one generated endpoint `.http` file for the root `README.md`.
pub(super) struct EndpointSummary {
    pub(super) file_path: String,
    pub(super) http_method: String,
    pub(super) route: String,
    pub(super) summary: String,
}

/// Renders `README.md` at the root of the output directory.
pub(super) fn render_readme(
    forge: &Forge,
    base_url: &str,
    endpoints: &[EndpointSummary],
    secrets: &BTreeSet<String>,
) -> HttpFile {
    let mut out = String::new();
    out.push_str("<!-- Generated by Forge. Do not edit. -->\n\n");
    out.push_str("# HTTP requests\n\n");

    let mut meta = Vec::new();
    if !forge.version.trim().is_empty() {
        meta.push(format!("Version `{}`", sanitize_inline(&forge.version)));
    }
    meta.push(format!("Base URL `{base_url}`"));
    let _ = writeln!(out, "{}.\n", meta.join(" · "));

    let desc = normalize_lf(&forge.description);
    let desc = desc.trim();
    if !desc.is_empty() {
        out.push_str(desc);
        out.push_str("\n\n");
    }

    if !secrets.is_empty() {
        out.push_str("## Secrets and environment setup\n\n");
        let vars = secrets
            .iter()
            .map(|s| format!("`{{{{{s}}}}}`"))
            .collect::<Vec<_>>()
            .join(", ");
        let _ = writeln!(
            out,
            "Generated `.http` files never assign secret values. Supply {vars} through your HTTP client's gitignored environment store:\n"
        );

        out.push_str("### JetBrains HTTP Client, Visual Studio, and kulala (`http-client.private.env.json`)\n\n");
        out.push_str("```json\n{\n  \"dev\": {\n");
        for (i, secret) in secrets.iter().enumerate() {
            let comma = if i + 1 < secrets.len() { "," } else { "" };
            let _ = writeln!(out, "    \"{secret}\": \"\"{comma}");
        }
        out.push_str("  }\n}\n```\n\n");

        out.push_str("### httpyac and kulala (`.env`)\n\n");
        out.push_str("```dotenv\n");
        for secret in secrets {
            let _ = writeln!(out, "{secret}=");
        }
        out.push_str("```\n\n");

        out.push_str("### VS Code REST Client (`.vscode/settings.json`)\n\n");
        out.push_str("```json\n{\n  \"rest-client.environmentVariables\": {\n    \"$shared\": {\n");
        for (i, secret) in secrets.iter().enumerate() {
            let comma = if i + 1 < secrets.len() { "," } else { "" };
            let _ = writeln!(out, "      \"{secret}\": \"\"{comma}");
        }
        out.push_str("    }\n  }\n}\n```\n\n");
    }

    out.push_str("## Endpoints\n\n");
    out.push_str("| Method | Path | File | Summary |\n");
    out.push_str("| --- | --- | --- | --- |\n");
    for ep in endpoints {
        let method = escape_table_cell(&ep.http_method);
        let route = escape_table_cell(&ep.route);
        let file = escape_table_cell(&ep.file_path);
        let summary = escape_table_cell(&ep.summary);
        let _ = writeln!(out, "| `{method}` | `{route}` | [{file}]({file}) | {summary} |");
    }

    HttpFile {
        path: "README.md".to_owned(),
        content: out,
    }
}

fn sanitize_inline(s: &str) -> String {
    s.split_whitespace().collect::<Vec<_>>().join(" ")
}

fn escape_table_cell(s: &str) -> String {
    sanitize_inline(s).replace('|', "\\|")
}
