//! Renders a single Forge [`Method`] into an `.http` file.

use std::collections::{BTreeSet, HashMap, HashSet};
use std::fmt::Write as _;

use forge::{Content, Field, Forge, Location, Method, Name, Scalar, Type};

use super::HttpFile;
use super::synth::{
    SynthCtx, VarScope, array_count, binary_array_count, escape_quoted_string, is_binary, normalize_lf, object_fields,
    percent_encode, sanitize_filename_stem, synth_json, synth_scalar, unwrap_type,
};

const GENERATED_HEADER: &str = "# Generated by Forge. Do not edit.";
const FALLBACK_BASE_URL: &str = "http://localhost:8080";
const DEFAULT_BOUNDARY: &str = "ForgeBoundary";

/// Renders `method` as a standalone `.http` file at `<group-path>/<method>.http`.
pub(super) fn render_method(forge: &Forge, method: Method<'_>) -> HttpFile {
    let path = file_path(method);
    let base_url = resolve_base_url(&forge.base_url);

    let mut path_params = Vec::new();
    let mut query_params = Vec::new();
    for field in request_fields(method.request()) {
        match method.location(field) {
            Some(Location::Path) => path_params.push(field),
            Some(Location::Query { exploded }) => query_params.push((field, exploded)),
            None => {}
        }
    }

    let declared_headers: Vec<Field<'_>> = method
        .headers()
        .into_iter()
        .flat_map(|obj| obj.fields())
        .filter(|f| !f.is_read_only())
        .collect();
    let has_authorization = has_header(&declared_headers, "authorization");
    let has_accept = has_header(&declared_headers, "accept");

    let mut vars = VarScope::default();
    if !has_authorization {
        // Reserve `token` so a non-sensitive path parameter named `{token}`
        // does not shadow `# Authorization: Bearer {{token}}`.
        vars.reserve("token");
    }

    let mut path_ctx = SynthCtx::new();
    let mut path_var_map: HashMap<&str, String> = HashMap::new();
    let mut declared_path_vars: Vec<(String, String)> = Vec::new();
    let mut declared_var_names: HashSet<String> = HashSet::new();

    for field in &path_params {
        let var = vars.alloc(field.name(), field.wire_name());
        if field.is_sensitive() {
            path_ctx.record_secret(&var);
        } else {
            let val = synth_scalar(field.ty(), Some(*field), Some(field.wire_name()), &mut path_ctx).as_plain();
            declared_path_vars.push((var.clone(), sanitize_single_line(&val)));
            declared_var_names.insert(var.clone());
        }
        path_var_map.insert(field.wire_name(), var);
    }

    let mut ctx = SynthCtx::with_declared(declared_var_names.clone());
    ctx.secrets.extend(path_ctx.secrets);

    let url_path = substitute_path(method.path(), &path_var_map);

    let mut required_query: Vec<(String, String)> = Vec::new();
    let mut optional_query: Vec<String> = Vec::new();
    for (field, exploded) in &query_params {
        let pairs = serialize_query_param(*field, *exploded, &mut ctx);
        if field.is_required() {
            required_query.extend(pairs);
        } else if !pairs.is_empty() {
            let joined = pairs
                .into_iter()
                .map(|(k, v)| format!("{k}={v}"))
                .collect::<Vec<_>>()
                .join("&");
            optional_query.push(joined);
        }
    }

    let accept_media = if has_accept { None } else { infer_accept(method) };

    let header_lines = render_declared_headers(&declared_headers, &mut ctx);
    if !has_authorization {
        ctx.record_secret("token");
    }

    let contents: Vec<Content<'_>> = method.body().into_iter().flat_map(|b| b.contents()).collect();
    let config = BlockConfig {
        method,
        url_path: &url_path,
        required_query: &required_query,
        optional_query: &optional_query,
        has_authorization,
        accept_media,
        declared_header_lines: &header_lines,
        declared_var_names: &declared_var_names,
        multi: contents.len() > 1,
    };
    let mut used_names = HashSet::new();
    let mut blocks = Vec::with_capacity(contents.len().max(1));

    if contents.is_empty() {
        blocks.push(render_block(&config, None, &mut used_names, &mut ctx.secrets));
    } else {
        for content in contents {
            blocks.push(render_block(&config, Some(content), &mut used_names, &mut ctx.secrets));
        }
    }

    let mut out = String::new();
    out.push_str(GENERATED_HEADER);
    out.push('\n');
    if !ctx.secrets.is_empty() {
        let list = ctx
            .secrets
            .iter()
            .map(|s| format!("{{{{{s}}}}}"))
            .collect::<Vec<_>>()
            .join(", ");
        let _ = writeln!(out, "# Secret: supply {list} via your HTTP client's environment.");
    }
    out.push('\n');
    let _ = writeln!(out, "@baseUrl = {base_url}");
    for (var, val) in &declared_path_vars {
        let _ = writeln!(out, "@{var} = {val}");
    }
    for block in &blocks {
        out.push('\n');
        out.push_str(block);
    }

    HttpFile { path, content: out }
}

/// Returns the output path for `method`: `<group-kebab>/<method-kebab>.http`.
fn file_path(method: Method<'_>) -> String {
    let mut parts: Vec<String> = method.group().path().map(Name::kebab).collect();
    parts.push(format!("{}.http", method.name().kebab()));
    parts.join("/")
}

fn resolve_base_url(base_url: &str) -> String {
    let trimmed = base_url.trim().trim_end_matches('/');
    if trimmed.is_empty() {
        FALLBACK_BASE_URL.to_owned()
    } else {
        sanitize_single_line(trimmed)
    }
}

/// Recursively collects the fields of a method's request (object of parameters
/// or intersection of parameters and body), matching `mcp.rs`.
fn request_fields(request: Option<Type<'_>>) -> Vec<Field<'_>> {
    match request {
        Some(Type::Object(object)) => object.fields().collect(),
        Some(Type::Intersection(intersection)) => intersection
            .members()
            .flat_map(|member| request_fields(Some(member)))
            .collect(),
        _ => Vec::new(),
    }
}

fn substitute_path(template: &str, path_vars: &HashMap<&str, String>) -> String {
    let mut out = String::with_capacity(template.len() + 16);
    if !template.is_empty() && !template.starts_with('/') {
        out.push('/');
    }
    let mut rest = template;
    while let Some(start) = rest.find('{') {
        out.push_str(&rest[..start]);
        let after_brace = &rest[start + 1..];
        let Some(end) = after_brace.find('}') else {
            out.push_str(&rest[start..]);
            return out;
        };
        let placeholder = &after_brace[..end];
        if let Some(var) = path_vars.get(placeholder) {
            let _ = write!(out, "{{{{{var}}}}}");
        } else {
            let _ = write!(out, "{{{{{placeholder}}}}}");
        }
        rest = &after_brace[end + 1..];
    }
    out.push_str(rest);
    out
}

fn serialize_query_param<'f>(field: Field<'f>, exploded: bool, ctx: &mut SynthCtx<'f>) -> Vec<(String, String)> {
    let wire = percent_encode(field.wire_name());
    if field.is_sensitive() || field.default().is_some() {
        let val = synth_scalar(field.ty(), Some(field), None, ctx).as_encoded();
        return vec![(wire, val)];
    }

    match unwrap_type(field.ty()) {
        Type::Array(arr) => {
            let count = array_count(arr);
            if count == 0 {
                return Vec::new();
            }
            let elems: Vec<String> = (0..count)
                .map(|_| synth_scalar(arr.elem(), None, None, ctx).as_encoded())
                .collect();
            if exploded {
                elems.into_iter().map(|v| (wire.clone(), v)).collect()
            } else {
                vec![(wire, elems.join(","))]
            }
        }
        ty @ (Type::Object(_) | Type::Intersection(_)) => {
            let Some((fields, extra)) = object_fields(ty) else {
                let val = synth_scalar(ty, None, None, ctx).as_encoded();
                return vec![(wire, val)];
            };
            let pairs: Vec<(String, String)> = if !fields.is_empty() {
                fields
                    .into_iter()
                    .map(|f| {
                        let k = percent_encode(f.wire_name());
                        let v = synth_scalar(f.ty(), Some(f), None, ctx).as_encoded();
                        (k, v)
                    })
                    .collect()
            } else if let Some(extra_ty) = extra {
                let v = synth_scalar(extra_ty, None, None, ctx).as_encoded();
                vec![("key".to_owned(), v)]
            } else {
                Vec::new()
            };
            if pairs.is_empty() {
                return Vec::new();
            }
            if exploded {
                pairs
            } else {
                let joined = pairs
                    .into_iter()
                    .flat_map(|(k, v)| [k, v])
                    .collect::<Vec<_>>()
                    .join(",");
                vec![(wire, joined)]
            }
        }
        other => {
            let val = synth_scalar(other, None, None, ctx).as_encoded();
            vec![(wire, val)]
        }
    }
}

fn has_header(headers: &[Field<'_>], target_lower: &str) -> bool {
    headers.iter().any(|f| f.wire_name().eq_ignore_ascii_case(target_lower))
}

fn infer_accept(method: Method<'_>) -> Option<&str> {
    if let Some(media) = method
        .responses()
        .filter_map(|r| r.json())
        .map(|c| c.media_type())
        .find(|m| !is_wildcard(m))
    {
        return Some(media);
    }
    method
        .responses()
        .flat_map(|r| r.contents())
        .map(|c| c.media_type())
        .find(|m| !is_wildcard(m))
}

struct DeclaredHeader {
    is_content_type: bool,
    line: String,
}

fn render_declared_headers<'f>(headers: &[Field<'f>], ctx: &mut SynthCtx<'f>) -> Vec<DeclaredHeader> {
    headers
        .iter()
        .map(|field| {
            let value = serialize_header_value(*field, ctx);
            let value = sanitize_single_line(&value);
            let line = if field.is_required() {
                format!("{}: {value}", field.wire_name())
            } else {
                format!("# {}: {value}", field.wire_name())
            };
            DeclaredHeader {
                is_content_type: field.wire_name().eq_ignore_ascii_case("content-type"),
                line,
            }
        })
        .collect()
}

fn serialize_header_value<'f>(field: Field<'f>, ctx: &mut SynthCtx<'f>) -> String {
    if field.is_sensitive() || field.default().is_some() {
        return synth_scalar(field.ty(), Some(field), None, ctx).as_plain();
    }
    match unwrap_type(field.ty()) {
        Type::Array(arr) => {
            let count = array_count(arr);
            (0..count)
                .map(|_| synth_scalar(arr.elem(), None, None, ctx).as_plain())
                .collect::<Vec<_>>()
                .join(",")
        }
        other => synth_scalar(other, None, None, ctx).as_plain(),
    }
}

struct BlockConfig<'a, 'f> {
    method: Method<'f>,
    url_path: &'a str,
    required_query: &'a [(String, String)],
    optional_query: &'a [String],
    has_authorization: bool,
    accept_media: Option<&'f str>,
    declared_header_lines: &'a [DeclaredHeader],
    declared_var_names: &'a HashSet<String>,
    multi: bool,
}

fn render_block(
    config: &BlockConfig<'_, '_>,
    content: Option<Content<'_>>,
    used_names: &mut HashSet<String>,
    secrets: &mut BTreeSet<String>,
) -> String {
    let method = config.method;
    let mut out = String::new();
    let http_method = method.http_method().as_str();

    // 1. Heading
    let summary = sanitize_single_line(method.summary());
    let title = if summary.is_empty() {
        format!("{http_method} {}", method.path())
    } else {
        summary.clone()
    };
    if config.multi
        && let Some(c) = content
    {
        let _ = writeln!(out, "### {title} ({})", sanitize_single_line(c.media_type()));
    } else {
        let _ = writeln!(out, "### {title}");
    }

    // 2. Metadata comments
    let _ = writeln!(out, "# {http_method} {}", method.path());

    let description = method.description().trim();
    if !description.is_empty() && sanitize_single_line(description) != summary {
        write_comment_block(&mut out, description);
    }
    if let Some(availability) = method.availability() {
        let _ = writeln!(out, "# Availability: {}", availability.as_str());
    }
    if method.is_deprecated() {
        out.push_str("# @deprecated\n");
    }
    if method.is_hidden() {
        out.push_str("# Hidden\n");
    }
    if let Some(confirmation) = method.confirmation() {
        let trimmed = confirmation.trim();
        if trimmed.is_empty() {
            out.push_str("# Warning: This operation requires confirmation.\n");
        } else {
            let mut lines = trimmed.lines();
            if let Some(first) = lines.next() {
                let _ = writeln!(out, "# Warning: {}", first.trim_end_matches('\r'));
            }
            for line in lines {
                let line = line.trim_end_matches('\r');
                if line.is_empty() {
                    out.push_str("#\n");
                } else {
                    let _ = writeln!(out, "# {line}");
                }
            }
        }
    }
    for opt in config.optional_query {
        let _ = writeln!(out, "# Optional query: {opt}");
    }

    // `# @name` must sit on the line immediately before the request line.
    let req_name = alloc_request_name(method, content.filter(|_| config.multi), used_names);
    let _ = writeln!(out, "# @name {req_name}");

    // 3. Single-line request URL
    let _ = write!(out, "{http_method} {{{{baseUrl}}}}{}", config.url_path);
    if !config.required_query.is_empty() {
        out.push('?');
        for (i, (k, v)) in config.required_query.iter().enumerate() {
            if i > 0 {
                out.push('&');
            }
            let _ = write!(out, "{k}={v}");
        }
    }
    out.push('\n');

    // 4. Headers
    if !config.has_authorization {
        out.push_str("# Authorization: Bearer {{token}}\n");
    }
    if let Some(accept) = config.accept_media {
        let _ = writeln!(out, "Accept: {}", sanitize_single_line(accept));
    }

    let has_declared_content_type = config.declared_header_lines.iter().any(|h| h.is_content_type);
    let mut block_sets_content_type = false;
    let mut multipart_boundary: Option<String> = None;
    if let Some(c) = content {
        let media = c.media_type();
        let base = base_media_type(media);
        if base == "multipart/form-data" {
            let boundary = extract_boundary(media).unwrap_or_else(|| DEFAULT_BOUNDARY.to_owned());
            if extract_boundary(media).is_some() {
                let _ = writeln!(out, "Content-Type: {}", sanitize_single_line(media));
            } else {
                let _ = writeln!(
                    out,
                    "Content-Type: {}; boundary={boundary}",
                    sanitize_single_line(media)
                );
            }
            block_sets_content_type = true;
            multipart_boundary = Some(boundary);
        } else if is_wildcard(media) {
            if !has_declared_content_type {
                out.push_str("# Content-Type: application/octet-stream\n");
            }
        } else {
            let _ = writeln!(out, "Content-Type: {}", sanitize_single_line(media));
            block_sets_content_type = true;
        }
    }

    for header in config.declared_header_lines {
        if header.is_content_type && block_sets_content_type {
            continue;
        }
        out.push_str(&header.line);
        out.push('\n');
    }

    // 5. Request body
    if let Some(c) = content {
        let mut body_ctx = SynthCtx::with_declared(config.declared_var_names.clone());
        let body = render_body(c, multipart_boundary.as_deref(), &mut body_ctx);
        secrets.extend(body_ctx.secrets);
        if !body.is_empty() {
            out.push('\n');
            out.push_str(&body);
            if !body.ends_with('\n') {
                out.push('\n');
            }
        }
    }

    out
}

fn render_body<'f>(content: Content<'f>, boundary: Option<&str>, ctx: &mut SynthCtx<'f>) -> String {
    let media = content.media_type();
    let base = base_media_type(media);

    if content.is_json() {
        let val = synth_json(content.ty(), None, ctx);
        return serde_json::to_string_pretty(&val).unwrap_or_else(|_| "{}".to_owned());
    }

    if base == "application/x-www-form-urlencoded" {
        return render_form_urlencoded(content.ty(), ctx);
    }

    if base == "multipart/form-data" {
        let boundary = boundary.unwrap_or(DEFAULT_BOUNDARY);
        return render_multipart(content.ty(), boundary, ctx);
    }

    let unwrapped = unwrap_type(content.ty());
    if is_binary(content.ty())
        || ((base == "application/octet-stream" || is_wildcard(media))
            && matches!(unwrapped, Type::Scalar(Scalar::Unknown)))
    {
        return "< ./file.bin".to_owned();
    }

    if matches!(unwrapped, Type::Scalar(Scalar::Unknown)) {
        return "<body placeholder>".to_owned();
    }

    normalize_lf(&synth_scalar(content.ty(), None, None, ctx).as_plain())
}

fn render_form_urlencoded<'f>(ty: Type<'f>, ctx: &mut SynthCtx<'f>) -> String {
    let Some((fields, extra)) = object_fields(ty) else {
        return synth_scalar(ty, None, None, ctx).as_encoded();
    };
    let mut pairs = Vec::new();
    if !fields.is_empty() {
        for field in fields {
            let k = percent_encode(field.wire_name());
            let v = synth_scalar(field.ty(), Some(field), None, ctx).as_encoded();
            pairs.push(format!("{k}={v}"));
        }
    } else if let Some(extra_ty) = extra {
        let v = synth_scalar(extra_ty, None, None, ctx).as_encoded();
        pairs.push(format!("key={v}"));
    }
    pairs.join("&")
}

fn render_multipart<'f>(ty: Type<'f>, boundary: &str, ctx: &mut SynthCtx<'f>) -> String {
    let mut out = String::new();
    let mut wrote_part = false;

    if let Some((fields, extra)) = object_fields(ty) {
        if !fields.is_empty() {
            for field in fields {
                let wire = field.wire_name();
                let quoted_name = escape_quoted_string(wire);
                if let Some(count) = binary_array_count(field.ty()) {
                    for _ in 0..count {
                        write_multipart_file(&mut out, boundary, wire);
                        wrote_part = true;
                    }
                } else if is_binary(field.ty()) {
                    write_multipart_file(&mut out, boundary, wire);
                    wrote_part = true;
                } else if is_structured_part(field.ty()) && field.default().is_none() && !field.is_sensitive() {
                    let val = synth_json(field.ty(), Some(field), ctx);
                    let json = serde_json::to_string_pretty(&val).unwrap_or_else(|_| "{}".to_owned());
                    let _ = writeln!(out, "--{boundary}");
                    let _ = writeln!(out, "Content-Disposition: form-data; name=\"{quoted_name}\"");
                    out.push_str("Content-Type: application/json\n\n");
                    out.push_str(&json);
                    out.push('\n');
                    wrote_part = true;
                } else {
                    let val = normalize_lf(&synth_scalar(field.ty(), Some(field), None, ctx).as_plain());
                    let _ = writeln!(out, "--{boundary}");
                    let _ = writeln!(out, "Content-Disposition: form-data; name=\"{quoted_name}\"\n");
                    out.push_str(&val);
                    out.push('\n');
                    wrote_part = true;
                }
            }
        } else if let Some(extra_ty) = extra {
            if is_binary(extra_ty) {
                write_multipart_file(&mut out, boundary, "file");
            } else {
                let val = normalize_lf(&synth_scalar(extra_ty, None, None, ctx).as_plain());
                let _ = writeln!(out, "--{boundary}");
                out.push_str("Content-Disposition: form-data; name=\"key\"\n\n");
                out.push_str(&val);
                out.push('\n');
            }
            wrote_part = true;
        }
    }

    if !wrote_part {
        if is_binary(ty) || matches!(unwrap_type(ty), Type::Scalar(Scalar::Unknown)) {
            write_multipart_file(&mut out, boundary, "file");
        } else {
            let val = normalize_lf(&synth_scalar(ty, None, None, ctx).as_plain());
            let _ = writeln!(out, "--{boundary}");
            out.push_str("Content-Disposition: form-data; name=\"file\"\n\n");
            out.push_str(&val);
            out.push('\n');
        }
    }

    let _ = writeln!(out, "--{boundary}--");
    out
}

fn write_multipart_file(out: &mut String, boundary: &str, wire_name: &str) {
    let quoted_name = escape_quoted_string(wire_name);
    let filename = format!("{}.bin", sanitize_filename_stem(wire_name));
    let _ = writeln!(out, "--{boundary}");
    let _ = writeln!(
        out,
        "Content-Disposition: form-data; name=\"{quoted_name}\"; filename=\"{filename}\""
    );
    out.push_str("Content-Type: application/octet-stream\n\n");
    let _ = writeln!(out, "< ./{filename}");
}

fn is_structured_part(ty: Type<'_>) -> bool {
    matches!(
        unwrap_type(ty),
        Type::Object(_) | Type::Array(_) | Type::Intersection(_) | Type::Union(_)
    )
}

fn alloc_request_name(method: Method<'_>, media: Option<Content<'_>>, used: &mut HashSet<String>) -> String {
    let mut parts: Vec<String> = method.group().path().map(Name::camel).collect();
    parts.push(method.name().camel());
    if let Some(c) = media {
        parts.push(media_type_suffix(c.media_type()));
    }
    let base = parts.join("_");
    if used.insert(base.clone()) {
        return base;
    }
    for n in 2u32.. {
        let candidate = format!("{base}_{n}");
        if used.insert(candidate.clone()) {
            return candidate;
        }
    }
    unreachable!("u32 exhausted")
}

fn media_type_suffix(media_type: &str) -> String {
    let base = base_media_type(media_type);
    if is_wildcard(&base) {
        return "any".to_owned();
    }
    let raw = match base.split_once('/') {
        Some(("multipart", _)) => base.as_str(),
        Some((_, subtype)) => subtype,
        None => base.as_str(),
    };
    let name = Name::new(raw);
    if name.is_empty() {
        "body".to_owned()
    } else {
        name.camel()
    }
}

fn base_media_type(media_type: &str) -> String {
    media_type
        .split(';')
        .next()
        .unwrap_or_default()
        .trim()
        .to_ascii_lowercase()
}

fn is_wildcard(media_type: &str) -> bool {
    let base = base_media_type(media_type);
    base == "*/*" || base.ends_with("/*") || base.is_empty()
}

fn extract_boundary(media_type: &str) -> Option<String> {
    for param in media_type.split(';').skip(1) {
        let Some((key, val)) = param.split_once('=') else {
            continue;
        };
        if key.trim().eq_ignore_ascii_case("boundary") {
            let val = val.trim().trim_matches('"');
            if !val.is_empty() {
                return Some(val.to_owned());
            }
        }
    }
    None
}

fn write_comment_block(out: &mut String, text: &str) {
    for line in text.lines() {
        let line = line.trim_end_matches('\r');
        if line.is_empty() {
            out.push_str("#\n");
        } else {
            let _ = writeln!(out, "# {line}");
        }
    }
}

fn sanitize_single_line(s: &str) -> String {
    s.split_whitespace().collect::<Vec<_>>().join(" ")
}
