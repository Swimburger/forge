//! Self-validation for generated `.http` files and `README.md`.
//!
//! Runs automatically inside [`super::Generator::generate`] so malformed `.http`
//! syntax, variable shadowing, broken percent-encoding, invalid JSON bodies,
//! broken multipart framing, directive injection, or invalid `README.md` JSON
//! snippets fail generation before any file is written.

use std::collections::{BTreeSet, HashMap, HashSet};

use forge::{Method, Type};
use serde_json::Value;

use super::synth::{discriminated_variants, object_fields};

/// Result of validating one `.http` file.
pub(super) struct ValidatedHttpFile {
    pub(super) secret_vars: BTreeSet<String>,
    pub(super) blocks: Vec<ValidatedBlock>,
}

/// Parsed summary of a single `###` request block within a `.http` file.
pub(super) struct ValidatedBlock {
    pub(super) name: String,
    pub(super) json_body: Option<Value>,
}

/// Validates a single generated `.http` file against portable `.http` grammar,
/// RFC 9112 wire syntax after variable expansion, RFC 3986 percent-encoding,
/// JSON parseability, multipart framing, and variable/secret invariants.
pub(super) fn validate_http_file(path: &str, content: &str) -> Result<ValidatedHttpFile, String> {
    if !path.ends_with(".http") {
        return Err(format!("{path}: expected .http extension"));
    }
    if !content.ends_with('\n') {
        return Err(format!("{path}: missing trailing newline"));
    }
    if content.contains('\r') {
        return Err(format!("{path}: unexpected CR byte"));
    }
    if !content.starts_with("# Generated by Forge. Do not edit.\n") {
        return Err(format!("{path}: missing generated header"));
    }

    let sections: Vec<&str> = content.split("\n### ").collect();
    if sections.len() < 2 {
        return Err(format!("{path}: expected at least one `### ` request block"));
    }

    // 1. Validate preamble (`# ...`, blank lines, and `@var = value`).
    let preamble = sections[0];
    let mut declared_vars: HashMap<String, String> = HashMap::new();
    let mut secret_vars: BTreeSet<String> = BTreeSet::new();

    for line in preamble.lines() {
        if line.is_empty() {
            continue;
        }
        if let Some(rest) = line.strip_prefix("# Secret: supply ") {
            let list = rest
                .strip_suffix(" via your HTTP client's environment.")
                .ok_or_else(|| format!("{path}: malformed secret header: {line:?}"))?;
            for item in list.split(", ") {
                let var = item
                    .strip_prefix("{{")
                    .and_then(|s| s.strip_suffix("}}"))
                    .ok_or_else(|| format!("{path}: malformed secret var {item:?}"))?;
                if !is_valid_ident(var) {
                    return Err(format!("{path}: invalid secret variable name {var:?}"));
                }
                if !secret_vars.insert(var.to_owned()) {
                    return Err(format!("{path}: duplicate secret variable {var:?}"));
                }
            }
            continue;
        }
        if line.starts_with('#') {
            check_comment_directive(path, line, false)?;
            continue;
        }
        let Some(decl) = line.strip_prefix('@') else {
            return Err(format!("{path}: unexpected preamble line: {line:?}"));
        };
        let Some((lhs, rhs)) = decl.split_once(" = ") else {
            return Err(format!("{path}: malformed variable declaration: {line:?}"));
        };
        if !is_valid_ident(lhs) {
            return Err(format!("{path}: invalid variable name {lhs:?}"));
        }
        if rhs.is_empty() || rhs.trim() != rhs {
            return Err(format!("{path}: empty or padded variable value for @{lhs}"));
        }
        if rhs.bytes().any(|b| b <= 0x20 || b == 0x7F) {
            return Err(format!("{path}: whitespace or control char in @{lhs} = {rhs:?}"));
        }
        if rhs.contains("{{") || rhs.contains("}}") {
            return Err(format!("{path}: template braces inside @{lhs} value: {rhs:?}"));
        }
        if declared_vars.insert(lhs.to_owned(), rhs.to_owned()).is_some() {
            return Err(format!("{path}: duplicate @{lhs} declaration"));
        }
    }

    if !declared_vars.contains_key("baseUrl") {
        return Err(format!("{path}: missing @baseUrl declaration"));
    }
    for secret in &secret_vars {
        if declared_vars.contains_key(secret) {
            return Err(format!("{path}: declared @{secret} shadows secret {{{{{secret}}}}}"));
        }
    }

    // 2. Validate every `### ` request block.
    let mut seen_names: HashSet<String> = HashSet::new();
    let mut used_vars: HashSet<String> = HashSet::new();
    let mut blocks = Vec::with_capacity(sections.len() - 1);

    for (idx, block) in sections[1..].iter().enumerate() {
        let block = block.trim_end_matches('\n');
        let mut lines = block.lines().peekable();
        let heading = lines
            .next()
            .ok_or_else(|| format!("{path} block {idx}: missing heading"))?;
        if heading.is_empty() {
            return Err(format!("{path} block {idx}: empty heading"));
        }

        // Metadata comments until request line; last comment must be `# @name <id>`.
        let mut last_comment = None;
        while let Some(&line) = lines.peek() {
            if line.starts_with('#') {
                check_comment_directive(path, line, true)?;
                scan_templates(path, line, &declared_vars, &secret_vars, &mut used_vars)?;
                last_comment = Some(line);
                lines.next();
            } else {
                break;
            }
        }
        let name_line = last_comment.ok_or_else(|| format!("{path} block {idx}: missing comments"))?;
        let req_name = name_line
            .strip_prefix("# @name ")
            .ok_or_else(|| format!("{path} block {idx}: expected `# @name` before request line, got {name_line:?}"))?;
        if !is_valid_ident(req_name) {
            return Err(format!("{path} block {idx}: invalid `# @name` identifier {req_name:?}"));
        }
        if !seen_names.insert(req_name.to_owned()) {
            return Err(format!("{path}: duplicate `# @name {req_name}`"));
        }

        // Request line: `<METHOD> {{baseUrl}}...`
        let req_line = lines
            .next()
            .ok_or_else(|| format!("{path} block {idx}: missing request line"))?;
        let (method, url) = req_line
            .split_once(' ')
            .ok_or_else(|| format!("{path} block {idx}: malformed request line {req_line:?}"))?;
        if method.is_empty() || !method.bytes().all(|b| b.is_ascii_alphanumeric() || b == b'-') {
            return Err(format!("{path} block {idx}: invalid HTTP method {method:?}"));
        }
        if !url.starts_with("{{baseUrl}}") {
            return Err(format!(
                "{path} block {idx}: URL must start with {{{{baseUrl}}}}, got {url:?}"
            ));
        }
        let expanded_url = expand_templates(path, url, &declared_vars, &secret_vars, &mut used_vars)?;
        validate_expanded_url(path, idx, &expanded_url)?;

        // Headers until blank line or end of block.
        let mut content_type: Option<String> = None;
        let mut seen_singleton_headers: HashSet<String> = HashSet::new();
        for line in lines.by_ref() {
            if line.is_empty() {
                break;
            }
            if line.starts_with('#') {
                check_comment_directive(path, line, false)?;
                scan_templates(path, line, &declared_vars, &secret_vars, &mut used_vars)?;
                continue;
            }
            let (hname, hval) = line
                .split_once(':')
                .ok_or_else(|| format!("{path} block {idx}: malformed header {line:?}"))?;
            if !is_valid_header_token(hname) {
                return Err(format!("{path} block {idx}: invalid header name {hname:?}"));
            }
            let hval = hval.trim();
            if hval.is_empty() || hval.bytes().any(|b| b < 0x20 || b == 0x7F) {
                return Err(format!("{path} block {idx}: invalid header value for {hname:?}"));
            }
            scan_templates(path, hval, &declared_vars, &secret_vars, &mut used_vars)?;

            let lower = hname.to_ascii_lowercase();
            if matches!(lower.as_str(), "content-type" | "accept" | "authorization")
                && !seen_singleton_headers.insert(lower.clone())
            {
                return Err(format!("{path} block {idx}: duplicate active {hname} header"));
            }
            if lower == "accept" && hval.contains('*') {
                return Err(format!("{path} block {idx}: wildcard Accept header {hval:?}"));
            }
            if lower == "content-type" {
                let base = hval.split(';').next().unwrap_or_default().trim().to_ascii_lowercase();
                if base.is_empty() || base.contains('*') {
                    return Err(format!("{path} block {idx}: wildcard Content-Type header {hval:?}"));
                }
                content_type = Some(hval.to_owned());
            }
        }

        // Remaining lines are the body.
        let body_lines: Vec<&str> = lines.collect();
        for body_line in &body_lines {
            if body_line.starts_with("###") {
                return Err(format!(
                    "{path} block {idx}: body line starts with `###` request delimiter: {body_line:?}"
                ));
            }
        }
        let body = body_lines.join("\n");
        let expanded_body = expand_templates(path, &body, &declared_vars, &secret_vars, &mut used_vars)?;

        let json_body = if let Some(ct) = &content_type {
            validate_body_for_content_type(path, idx, ct, &body, &expanded_body)?
        } else if !body.is_empty() {
            validate_file_redirect_if_present(path, idx, &body)?;
            None
        } else {
            None
        };

        blocks.push(ValidatedBlock {
            name: req_name.to_owned(),
            json_body,
        });
    }

    // 3. Completeness: every declared `@var` and every listed secret must be used.
    for var in declared_vars.keys() {
        if !used_vars.contains(var) {
            return Err(format!("{path}: unused variable declaration @{var}"));
        }
    }
    for secret in &secret_vars {
        if !used_vars.contains(secret) {
            return Err(format!("{path}: unused secret variable {{{{{secret}}}}}"));
        }
    }

    Ok(ValidatedHttpFile { secret_vars, blocks })
}

/// Validates the generated root `README.md`: checks formatting, parses every
/// embedded ```json``` code block, and verifies all endpoints and secrets are
/// listed.
pub(super) fn validate_readme(
    content: &str,
    expected_http_paths: &[&str],
    expected_secrets: &BTreeSet<String>,
) -> Result<(), String> {
    if !content.ends_with('\n') {
        return Err("README.md: missing trailing newline".to_owned());
    }
    if content.contains('\r') {
        return Err("README.md: unexpected CR byte".to_owned());
    }
    if !content.starts_with("<!-- Generated by Forge. Do not edit. -->\n") {
        return Err("README.md: missing generated header".to_owned());
    }

    // Validate every fenced ```json block parses as valid JSON.
    let mut in_json = false;
    let mut json_buf = String::new();
    let mut json_blocks = 0usize;
    for line in content.lines() {
        if in_json {
            if line == "```" {
                serde_json::from_str::<Value>(&json_buf)
                    .map_err(|err| format!("README.md: invalid JSON code block #{json_blocks}: {err}\n{json_buf}"))?;
                json_buf.clear();
                in_json = false;
            } else {
                json_buf.push_str(line);
                json_buf.push('\n');
            }
        } else if line == "```json" {
            in_json = true;
            json_blocks += 1;
        }
    }
    if in_json {
        return Err("README.md: unclosed ```json code fence".to_owned());
    }

    if !expected_secrets.is_empty() {
        if json_blocks < 2 {
            return Err(format!(
                "README.md: expected at least 2 JSON setup snippets for secrets, found {json_blocks}"
            ));
        }
        for secret in expected_secrets {
            if !content.contains(&format!("`{{{{{secret}}}}}`")) {
                return Err(format!("README.md: missing secret `{{{{{secret}}}}}`"));
            }
            if !content.contains(&format!("{secret}=")) {
                return Err(format!("README.md: missing dotenv entry `{secret}=`"));
            }
        }
    }

    // Verify every generated `.http` file is linked and table row count matches.
    let mut table_rows = 0usize;
    let mut in_endpoints = false;
    for line in content.lines() {
        if line == "## Endpoints" {
            in_endpoints = true;
            continue;
        }
        if in_endpoints && line.starts_with("| `") {
            table_rows += 1;
        }
    }
    if table_rows != expected_http_paths.len() {
        return Err(format!(
            "README.md: endpoint table has {table_rows} rows, expected {}",
            expected_http_paths.len()
        ));
    }
    for path in expected_http_paths {
        let link = format!("[{path}]({path})");
        if !content.contains(&link) {
            return Err(format!("README.md: missing endpoint link {link}"));
        }
    }

    Ok(())
}

fn check_comment_directive(path: &str, line: &str, allow_block_directives: bool) -> Result<(), String> {
    // Neutralized lines use `## ...` and are never directives.
    if line.starts_with("##") {
        return Ok(());
    }
    let after_hash = line.strip_prefix('#').unwrap_or(line).trim_start();
    if after_hash.starts_with('@') {
        if allow_block_directives && (after_hash == "@deprecated" || after_hash.starts_with("@name ")) {
            return Ok(());
        }
        return Err(format!("{path}: unexpected comment directive {line:?}"));
    }
    Ok(())
}

fn scan_templates(
    path: &str,
    text: &str,
    declared: &HashMap<String, String>,
    secrets: &BTreeSet<String>,
    used: &mut HashSet<String>,
) -> Result<(), String> {
    let _ = expand_templates(path, text, declared, secrets, used)?;
    Ok(())
}

fn expand_templates(
    path: &str,
    text: &str,
    declared: &HashMap<String, String>,
    secrets: &BTreeSet<String>,
    used: &mut HashSet<String>,
) -> Result<String, String> {
    let mut out = String::with_capacity(text.len());
    let mut rest = text;
    while let Some(start) = rest.find("{{") {
        out.push_str(&rest[..start]);
        let after = &rest[start + 2..];
        let Some(end) = after.find("}}") else {
            return Err(format!("{path}: unclosed `{{{{` template in {text:?}"));
        };
        let var = &after[..end];
        if let Some(val) = declared.get(var) {
            used.insert(var.to_owned());
            out.push_str(val);
        } else if secrets.contains(var) {
            used.insert(var.to_owned());
            out.push_str("secret_value");
        } else {
            return Err(format!("{path}: undeclared variable reference {{{{{var}}}}}"));
        }
        rest = &after[end + 2..];
    }
    out.push_str(rest);
    Ok(out)
}

fn validate_expanded_url(path: &str, idx: usize, url: &str) -> Result<(), String> {
    if url.bytes().any(|b| b <= 0x20 || b == 0x7F) {
        return Err(format!(
            "{path} block {idx}: whitespace or control char in expanded URL {url:?}"
        ));
    }
    if url.contains('{') || url.contains('}') {
        return Err(format!("{path} block {idx}: unexpanded brace in expanded URL {url:?}"));
    }
    if url.matches('?').count() > 1 {
        return Err(format!("{path} block {idx}: multiple `?` in expanded URL {url:?}"));
    }
    validate_percent_encoding(path, idx, url, "URL")?;
    if let Some((_, query)) = url.split_once('?') {
        for pair in query.split('&') {
            let Some((k, _)) = pair.split_once('=') else {
                return Err(format!(
                    "{path} block {idx}: malformed query segment {pair:?} in URL {url:?}"
                ));
            };
            if k.is_empty() {
                return Err(format!("{path} block {idx}: empty query key in URL {url:?}"));
            }
        }
    }
    Ok(())
}

fn validate_percent_encoding(path: &str, idx: usize, s: &str, context: &str) -> Result<(), String> {
    let bytes = s.as_bytes();
    let mut i = 0;
    while i < bytes.len() {
        if bytes[i] == b'%' {
            if i + 2 >= bytes.len() || !bytes[i + 1].is_ascii_hexdigit() || !bytes[i + 2].is_ascii_hexdigit() {
                return Err(format!(
                    "{path} block {idx}: invalid percent-encoding in {context}: {s:?}"
                ));
            }
            i += 3;
        } else {
            i += 1;
        }
    }
    Ok(())
}

fn validate_body_for_content_type(
    path: &str,
    idx: usize,
    ct: &str,
    raw_body: &str,
    expanded_body: &str,
) -> Result<Option<Value>, String> {
    let base = ct.split(';').next().unwrap_or_default().trim().to_ascii_lowercase();
    if base == "application/json" || base.ends_with("+json") {
        let parsed: Value = serde_json::from_str(raw_body)
            .map_err(|err| format!("{path} block {idx}: invalid JSON body: {err}\n{raw_body}"))?;
        let _: Value = serde_json::from_str(expanded_body)
            .map_err(|err| format!("{path} block {idx}: invalid expanded JSON body: {err}\n{expanded_body}"))?;
        return Ok(Some(parsed));
    }

    if base == "application/x-www-form-urlencoded" {
        if !expanded_body.is_empty() {
            if expanded_body.contains('\n') || expanded_body.bytes().any(|b| b <= 0x20 || b == 0x7F) {
                return Err(format!(
                    "{path} block {idx}: whitespace or newline in form-urlencoded body: {expanded_body:?}"
                ));
            }
            validate_percent_encoding(path, idx, expanded_body, "form body")?;
        }
        return Ok(None);
    }

    if base == "multipart/form-data" {
        validate_multipart_body(path, idx, ct, raw_body)?;
        return Ok(None);
    }

    validate_file_redirect_if_present(path, idx, raw_body)?;
    Ok(None)
}

fn validate_multipart_body(path: &str, idx: usize, ct: &str, body: &str) -> Result<(), String> {
    let boundary = extract_boundary_param(ct)
        .ok_or_else(|| format!("{path} block {idx}: multipart header missing boundary: {ct}"))?;
    if boundary.bytes().any(|b| b <= 0x20 || b == 0x7F) {
        return Err(format!(
            "{path} block {idx}: invalid whitespace/control char in multipart boundary {boundary:?}"
        ));
    }
    let open = format!("--{boundary}");
    let close = format!("--{boundary}--");
    if !body.starts_with(&format!("{open}\n")) {
        return Err(format!("{path} block {idx}: multipart body does not start with {open}"));
    }
    if !body.ends_with(&close) {
        return Err(format!("{path} block {idx}: multipart body does not end with {close}"));
    }
    if body.matches(&close).count() != 1 {
        return Err(format!(
            "{path} block {idx}: multipart closing delimiter {close} appears more than once"
        ));
    }
    let inner = body
        .strip_prefix(&format!("{open}\n"))
        .and_then(|s| s.strip_suffix(&close))
        .ok_or_else(|| format!("{path} block {idx}: malformed multipart envelope"))?;

    for part in inner.split(&format!("\n{open}\n")) {
        let (part_headers, part_body) = part
            .split_once("\n\n")
            .ok_or_else(|| format!("{path} block {idx}: malformed multipart part:\n{part}"))?;
        let disposition = part_headers
            .lines()
            .find(|l| l.starts_with("Content-Disposition: form-data;"))
            .ok_or_else(|| format!("{path} block {idx}: missing Content-Disposition:\n{part_headers}"))?;
        if !disposition.contains("name=\"") {
            return Err(format!(
                "{path} block {idx}: Content-Disposition missing name parameter: {disposition:?}"
            ));
        }
        // Part body must never contain the boundary delimiter (framing safety).
        let trimmed_part_body = part_body.trim_end_matches('\n');
        if trimmed_part_body.contains(&open) {
            return Err(format!(
                "{path} block {idx}: multipart part body contains boundary {open:?}"
            ));
        }
        if part_headers.contains("Content-Type: application/json") {
            serde_json::from_str::<Value>(trimmed_part_body).map_err(|err| {
                format!("{path} block {idx}: invalid JSON multipart part: {err}\n{trimmed_part_body}")
            })?;
        }
        if let Some(filename) = extract_quoted_param(disposition, "filename") {
            if filename.is_empty() || filename.contains('/') || filename.contains("..") || filename.contains('\\') {
                return Err(format!("{path} block {idx}: unsafe multipart filename {filename:?}"));
            }
            let expected_redirect = format!("< ./{filename}");
            if trimmed_part_body != expected_redirect {
                return Err(format!(
                    "{path} block {idx}: expected file part body {expected_redirect:?}, got {trimmed_part_body:?}"
                ));
            }
        }
    }
    Ok(())
}

fn validate_file_redirect_if_present(path: &str, idx: usize, body: &str) -> Result<(), String> {
    if let Some(target) = body.strip_prefix("< ") {
        if target.contains('\n') {
            return Err(format!("{path} block {idx}: multiline file redirect: {body:?}"));
        }
        let rel = target.strip_prefix("./").unwrap_or(target);
        if rel.is_empty() || rel.contains('/') || rel.contains("..") || rel.contains('\\') {
            return Err(format!("{path} block {idx}: unsafe file redirect target {target:?}"));
        }
    }
    Ok(())
}

fn extract_boundary_param(ct: &str) -> Option<String> {
    let mut in_quotes = false;
    let mut start = 0usize;
    let mut segments = Vec::new();
    for (i, ch) in ct.char_indices() {
        match ch {
            '"' => in_quotes = !in_quotes,
            ';' if !in_quotes => {
                segments.push(&ct[start..i]);
                start = i + 1;
            }
            _ => {}
        }
    }
    segments.push(&ct[start..]);
    for param in segments.into_iter().skip(1) {
        let Some((k, v)) = param.split_once('=') else {
            continue;
        };
        if k.trim().eq_ignore_ascii_case("boundary") {
            let v = v.trim().trim_matches('"').trim();
            if !v.is_empty() {
                return Some(v.to_owned());
            }
        }
    }
    None
}

fn extract_quoted_param<'a>(header: &'a str, key: &str) -> Option<&'a str> {
    let needle = format!("{key}=\"");
    let start = header.find(&needle)? + needle.len();
    let rest = &header[start..];
    let end = rest.find('"')?;
    Some(&rest[..end])
}

fn is_valid_ident(s: &str) -> bool {
    !s.is_empty()
        && (s.as_bytes()[0].is_ascii_alphabetic() || s.as_bytes()[0] == b'_')
        && s.bytes().all(|b| b.is_ascii_alphanumeric() || b == b'_')
}

fn is_valid_header_token(s: &str) -> bool {
    !s.is_empty()
        && s.bytes().all(|b| {
            b.is_ascii_alphanumeric()
                || matches!(
                    b,
                    b'!' | b'#'
                        | b'$'
                        | b'%'
                        | b'&'
                        | b'\''
                        | b'*'
                        | b'+'
                        | b'-'
                        | b'.'
                        | b'^'
                        | b'_'
                        | b'`'
                        | b'|'
                        | b'~'
                )
        })
}

/// Validates a generated `.http` file's JSON bodies against its source
/// [`Method`] (`readOnly` omission, required-field presence, minimal/full
/// separation, and discriminator values).
pub(super) fn validate_method_conformance(
    method: Method<'_>,
    path: &str,
    validated: &ValidatedHttpFile,
) -> Result<(), String> {
    let Some(body) = method.body() else {
        return Ok(());
    };
    let json_contents: Vec<_> = body.contents().filter(|c| c.is_json()).collect();
    if json_contents.len() != 1 {
        return Ok(());
    }
    let content = json_contents[0];
    let json_blocks: Vec<_> = validated.blocks.iter().filter(|b| b.json_body.is_some()).collect();

    // Check discriminated union variants carry their exact discriminator key.
    if let Some(disc) = discriminated_variants(content.ty()) {
        for block in &json_blocks {
            let Some(Value::Object(map)) = &block.json_body else {
                continue;
            };
            if let Some(Value::String(actual)) = map.get(disc.wire_name) {
                let known = disc.cases.iter().any(|&(k, _)| k == actual);
                if !known {
                    return Err(format!(
                        "{path}: block {:?} has unknown discriminator {} = {actual:?}",
                        block.name, disc.wire_name
                    ));
                }
            }
        }
        return Ok(());
    }

    // For plain object JSON bodies, check readOnly omission and required/optional conformance.
    if let Some((fields, _)) = object_fields(content.ty()) {
        let read_only = collect_read_only_names(content.ty());
        let required: HashSet<&str> = fields
            .iter()
            .filter(|f| f.is_required())
            .map(|f| f.wire_name())
            .collect();
        let all_sendable: HashSet<&str> = fields.iter().map(|f| f.wire_name()).collect();

        for block in &json_blocks {
            let Some(Value::Object(map)) = &block.json_body else {
                continue;
            };
            for ro in &read_only {
                if map.contains_key(*ro) {
                    return Err(format!("{path}: block {:?} emitted readOnly field {ro:?}", block.name));
                }
            }
            for req in &required {
                if !map.contains_key(*req) {
                    return Err(format!("{path}: block {:?} omitted required field {req:?}", block.name));
                }
            }
            if block.name.ends_with("_minimal") {
                for key in map.keys() {
                    if !required.contains(key.as_str()) {
                        return Err(format!(
                            "{path}: minimal block {:?} included optional field {key:?}",
                            block.name
                        ));
                    }
                }
            } else if block.name.ends_with("_full") {
                for field_name in &all_sendable {
                    if !map.contains_key(*field_name) {
                        return Err(format!(
                            "{path}: full block {:?} omitted sendable field {field_name:?}",
                            block.name
                        ));
                    }
                }
            }
        }
    }
    Ok(())
}

fn collect_read_only_names<'f>(ty: Type<'f>) -> HashSet<&'f str> {
    match ty {
        Type::Model(m) => collect_read_only_names(m.ty()),
        Type::Object(obj) => obj
            .fields()
            .filter(|f| f.is_read_only())
            .map(|f| f.wire_name())
            .collect(),
        _ => HashSet::new(),
    }
}

#[cfg(test)]
pub(super) mod model_check {
    use std::collections::BTreeMap;

    use forge::{Forge, Method, Name};

    use super::{validate_http_file, validate_method_conformance, validate_readme};

    /// Validates an entire generated file map against both `.http` syntax rules
    /// and the source [`Forge`] model (1:1 endpoint coverage, `readOnly`
    /// omission, required-field presence, minimal/full separation, and
    /// discriminator values).
    pub(crate) fn validate_against_forge(forge: &Forge, files: &BTreeMap<String, String>) -> Result<(), String> {
        let methods: Vec<Method<'_>> = forge.groups().flat_map(|g| g.methods()).collect();
        let mut expected_paths: Vec<String> = Vec::with_capacity(methods.len());
        let mut all_secrets = std::collections::BTreeSet::new();

        for &method in &methods {
            let mut parts: Vec<String> = method.group().path().map(Name::kebab).collect();
            parts.push(format!("{}.http", method.name().kebab()));
            let path = parts.join("/");
            let content = files
                .get(&path)
                .ok_or_else(|| format!("missing generated file {path} for method {:?}", method.name()))?;
            let validated = validate_http_file(&path, content)?;
            validate_method_conformance(method, &path, &validated)?;
            all_secrets.extend(validated.secret_vars);
            expected_paths.push(path);
        }

        expected_paths.sort();
        let expected_refs: Vec<&str> = expected_paths.iter().map(String::as_str).collect();

        if methods.is_empty() {
            if !files.is_empty() {
                return Err(format!("expected 0 files for empty forge, got {}", files.len()));
            }
        } else {
            let expected_count = methods.len() + 1; // `.http` files + README.md
            if files.len() != expected_count {
                return Err(format!(
                    "expected {expected_count} files ({} endpoints + README.md), got {}",
                    methods.len(),
                    files.len()
                ));
            }
            let readme = files
                .get("README.md")
                .ok_or_else(|| "missing root README.md".to_owned())?;
            validate_readme(readme, &expected_refs, &all_secrets)?;
        }

        Ok(())
    }
}
