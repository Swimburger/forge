    #[test]
    fn skips() {
        let tools = tools(
            r#"{"openapi": "3.1.0", "info": {"title": "t", "version": "1"},
                "paths": {
                    "/hidden": {"get": {"x-fern-sdk-group-name": "a", "x-fern-sdk-method-name": "hidden",
                        "x-forge-hidden": true, "responses": {"200": {"description": "ok"}}}},
                    "/upload": {"put": {"x-fern-sdk-group-name": "a", "x-fern-sdk-method-name": "upload",
                        "requestBody": {"content": {"application/octet-stream": {"schema": {"type": "string"}}}},
                        "responses": {"200": {"description": "ok"}}}},
                    "/download": {"get": {"x-fern-sdk-group-name": "a", "x-fern-sdk-method-name": "download",
                        "responses": {"200": {"description": "ok",
                            "content": {"application/pdf": {"schema": {"type": "string"}}}}}}},
                    "/header": {"get": {"x-fern-sdk-group-name": "a", "x-fern-sdk-method-name": "header",
                        "parameters": [{"name": "X-Key", "in": "header", "required": true, "schema": {"type": "string"}}],
                        "responses": {"200": {"description": "ok"}}}},
                    "/text": {"get": {"x-fern-sdk-group-name": "a", "x-fern-sdk-method-name": "text",
                        "responses": {"200": {"description": "ok",
                            "content": {"text/csv": {"schema": {"type": "string"}}}}}}}
                }}"#,
        );
        for skipped in ["a_hidden", "a_upload", "a_download", "a_header"] {
            assert!(!tools.contains(&format!("\"{skipped}\"")), "{skipped}: {tools}");
        }
        assert!(tools.contains(r#"name: "a_text","#), "{tools}");
    }

