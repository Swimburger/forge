//! The HTTP file generator, following `rfcs/http-file.md`.
//!
//! Generates portable `.http` request files from an OpenAPI document: groups
//! become folders in `kebab-case`, and every endpoint becomes its own `.http`
//! file with self-contained `@var` declarations and one `###` request block
//! per request media type.

use std::borrow::Cow;
use std::collections::BTreeSet;

use forge::{Err, Forge, Method, Plugin};
use rayon::prelude::*;

mod readme;
mod render;
mod synth;

/// Generates `.http` request files and a root `README.md` for a [`Forge`].
pub struct Generator;

/// A generated file (`.http` request file or `README.md`).
pub struct HttpFile {
    path: String,
    content: String,
}

impl forge::File for HttpFile {
    fn path(&self) -> &str {
        &self.path
    }

    fn content(&self) -> Result<Cow<'_, [u8]>, Err> {
        Ok(Cow::Borrowed(self.content.as_bytes()))
    }
}

impl Plugin for Generator {
    type File = HttpFile;

    /// Generates one `.http` file per method across every group in parallel,
    /// plus a root `README.md` index when the document has at least one method.
    fn generate(&self, forge: &Forge) -> Result<impl Iterator<Item = HttpFile>, Err> {
        let methods: Vec<Method<'_>> = forge.groups().flat_map(|g| g.methods()).collect();
        let mut rendered: Vec<render::RenderedEndpoint> = methods
            .par_iter()
            .map(|&method| render::render_method(forge, method))
            .collect();
        rendered.sort_by(|a, b| a.summary.file_path.cmp(&b.summary.file_path));

        let mut secrets = BTreeSet::new();
        let mut summaries = Vec::with_capacity(rendered.len());
        let mut files = Vec::with_capacity(rendered.len() + 1);
        for ep in rendered {
            secrets.extend(ep.secrets);
            summaries.push(ep.summary);
            files.push(ep.file);
        }
        if !summaries.is_empty() {
            let base_url = render::resolve_base_url(&forge.base_url);
            files.push(readme::render_readme(forge, &base_url, &summaries, &secrets));
        }
        Ok(files.into_iter())
    }
}

