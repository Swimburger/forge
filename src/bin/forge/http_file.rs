//! The HTTP file generator, following `rfcs/http-file.md`.
//!
//! Generates portable `.http` request files from an OpenAPI document: groups
//! become folders in `kebab-case`, and every endpoint becomes its own `.http`
//! file with self-contained `@var` declarations and one `###` request block
//! per request media type.

use std::borrow::Cow;

use forge::{Err, Forge, Method, Plugin};
use rayon::prelude::*;

mod render;
mod synth;

/// Generates `.http` request files for every method in a [`Forge`].
pub struct Generator;

/// A generated `.http` file.
pub struct HttpFile {
    path: String,
    content: String,
}

impl forge::File for HttpFile {
    fn path(&self) -> &str {
        &self.path
    }

    fn content(&self) -> Result<Cow<'_, [u8]>, Err> {
        Ok(Cow::Borrowed(self.content.as_bytes()))
    }
}

impl Plugin for Generator {
    type File = HttpFile;

    /// Generates one `.http` file per method across every group in parallel.
    fn generate(&self, forge: &Forge) -> Result<impl Iterator<Item = HttpFile>, Err> {
        let methods: Vec<Method<'_>> = forge.groups().flat_map(|g| g.methods()).collect();
        let files: Vec<HttpFile> = methods
            .par_iter()
            .map(|&method| render::render_method(forge, method))
            .collect();
        Ok(files.into_iter())
    }
}

