    fn build_paths(paths: &str) -> Forge {
        let doc = format!(
            r#"{{
              "openapi": "3.0.3",
              "info": {{"title": "t", "version": "1"}},
              "servers": [{{"url": "https://api.example.com/"}}],
              "paths": {paths}
            }}"#
        );
        build(&doc)
    }

    fn generate(forge: &Forge) -> BTreeMap<String, String> {
        let files: BTreeMap<String, String> = Generator
            .generate(forge)
            .unwrap()
            .map(|file| {
                let content = forge::File::content(&file).unwrap();
                let content = String::from_utf8(content.into_owned()).unwrap();
                (forge::File::path(&file).to_owned(), content)
            })
            .collect();
        let mut http_paths = Vec::new();
        for (path, content) in &files {
            if path == "README.md" {
                assert!(content.ends_with('\n'), "README.md: missing trailing newline");
                assert!(!content.contains('\r'), "README.md: unexpected CR byte");
                assert!(content.starts_with("<!-- Generated by Forge. Do not edit. -->\n"));
            } else {
                validate_http_file(path, content);
                http_paths.push(path.as_str());
            }
        }
        if !http_paths.is_empty() {
            let readme = files.get("README.md").expect("README.md should be generated");
            for path in &http_paths {
                assert!(
                    readme.contains(&format!("[{path}]({path})")),
                    "README.md missing link to {path}:\n{readme}"
                );
            }
        }
        // Determinism check: a second run must produce byte-identical output.
        let second: BTreeMap<String, String> = Generator
            .generate(forge)
            .unwrap()
            .map(|file| {
                let content = forge::File::content(&file).unwrap();
                let content = String::from_utf8(content.into_owned()).unwrap();
                (forge::File::path(&file).to_owned(), content)
            })
            .collect();
        assert_eq!(files, second, "output is not deterministic");
        files
    }

    /// Strict structural validator for generated `.http` files: verifies the
    /// header comment, `@var` syntax, `###` delimiters, `# @name` and
    /// single-line request line pairing, valid header blocks, parseable JSON
    /// bodies, and balanced multipart boundaries.
    fn validate_http_file(path: &str, content: &str) {
        assert!(path.ends_with(".http"), "{path}: expected .http extension");
        assert!(content.ends_with('\n'), "{path}: missing trailing newline");
        assert!(!content.contains('\r'), "{path}: unexpected CR byte");
        assert!(
            content.starts_with("# Generated by Forge. Do not edit.\n"),
            "{path}: missing generated header"
        );

        let sections: Vec<&str> = content.split("\n### ").collect();
        assert!(
            sections.len() >= 2,
            "{path}: expected at least one `### ` request block"
        );

        // Validate preamble (`# ...`, blank lines, and `@var = val`).
        let preamble = sections[0];
        let mut declared_vars = std::collections::HashSet::new();
        let mut secret_vars = std::collections::HashSet::new();
        for line in preamble.lines() {
            if line.is_empty() {
                continue;
            }
            if let Some(rest) = line.strip_prefix("# Secret: supply ") {
                let list = rest
                    .strip_suffix(" via your HTTP client's environment.")
                    .unwrap_or_else(|| panic!("{path}: malformed secret header: {line:?}"));
                for item in list.split(", ") {
                    let var = item
                        .strip_prefix("{{")
                        .and_then(|s| s.strip_suffix("}}"))
                        .unwrap_or_else(|| panic!("{path}: malformed secret var {item:?}"));
                    secret_vars.insert(var.to_owned());
                }
                continue;
            }
            if line.starts_with('#') {
                continue;
            }
            assert!(line.starts_with('@'), "{path}: unexpected preamble line: {line:?}");
            let Some((lhs, _rhs)) = line[1..].split_once(" = ") else {
                panic!("{path}: malformed variable declaration: {line:?}");
            };
            assert!(
                !lhs.is_empty() && lhs.bytes().all(|b| b.is_ascii_alphanumeric() || b == b'_'),
                "{path}: invalid variable name {lhs:?}"
            );
            assert!(
                declared_vars.insert(lhs.to_owned()),
                "{path}: duplicate @{lhs} declaration"
            );
        }
        assert!(
            declared_vars.contains("baseUrl"),
            "{path}: missing @baseUrl declaration"
        );
        for secret in &secret_vars {
            assert!(
                !declared_vars.contains(secret),
                "{path}: declared @{secret} shadows secret {{{{{secret}}}}}"
            );
        }

        // Every `{{var}}` referenced in any request block must be declared or
        // listed as a secret.
        let mut rest = content;
        while let Some(start) = rest.find("{{") {
            let after = &rest[start + 2..];
            let Some(end) = after.find("}}") else {
                break;
            };
            let var = &after[..end];
            assert!(
                declared_vars.contains(var) || secret_vars.contains(var),
                "{path}: undeclared variable reference {{{{{var}}}}}"
            );
            rest = &after[end + 2..];
        }

        // Validate each `### ` request block.
        let mut seen_names = std::collections::HashSet::new();
        for (idx, block) in sections[1..].iter().enumerate() {
            let block = block.trim_end_matches('\n');
            let mut lines = block.lines().peekable();
            let heading = lines.next().expect("heading line");
            assert!(!heading.is_empty(), "{path} block {idx}: empty heading");

            // Comment lines until request line; last comment must be `# @name <id>`.
            let mut last_comment = None;
            while let Some(&line) = lines.peek() {
                if line.starts_with('#') {
                    last_comment = Some(line);
                    lines.next();
                } else {
                    break;
                }
            }
            let name_line = last_comment.unwrap_or_else(|| panic!("{path} block {idx}: missing comments"));
            let req_name = name_line.strip_prefix("# @name ").unwrap_or_else(|| {
                panic!("{path} block {idx}: expected `# @name` before request line, got {name_line:?}")
            });
            assert!(
                !req_name.is_empty()
                    && (req_name.as_bytes()[0].is_ascii_alphabetic() || req_name.as_bytes()[0] == b'_')
                    && req_name.bytes().all(|b| b.is_ascii_alphanumeric() || b == b'_'),
                "{path} block {idx}: invalid `# @name` identifier {req_name:?}"
            );
            assert!(
                seen_names.insert(req_name.to_owned()),
                "{path}: duplicate `# @name {req_name}`"
            );

            // Request line: `<METHOD> {{baseUrl}}...`
            let req_line = lines
                .next()
                .unwrap_or_else(|| panic!("{path} block {idx}: missing request line"));
            let (method, url) = req_line
                .split_once(' ')
                .unwrap_or_else(|| panic!("{path} block {idx}: malformed request line {req_line:?}"));
            assert!(
                !method.is_empty() && method.bytes().all(|b| b.is_ascii_alphanumeric() || b == b'-'),
                "{path} block {idx}: invalid HTTP method {method:?}"
            );
            assert!(
                url.starts_with("{{baseUrl}}"),
                "{path} block {idx}: URL must start with {{{{baseUrl}}}}, got {url:?}"
            );
            assert!(!url.contains(' '), "{path} block {idx}: unencoded space in URL {url:?}");

            // Headers until blank line or end of block.
            let mut content_type: Option<String> = None;
            for line in lines.by_ref() {
                if line.is_empty() {
                    break;
                }
                if line.starts_with('#') {
                    continue;
                }
                let (hname, hval) = line
                    .split_once(':')
                    .unwrap_or_else(|| panic!("{path} block {idx}: malformed header {line:?}"));
                assert!(
                    !hname.is_empty() && !hname.contains(' '),
                    "{path}: bad header name {hname:?}"
                );
                if hname.eq_ignore_ascii_case("content-type") {
                    content_type = Some(hval.trim().to_owned());
                }
            }

            // Remaining lines are the body.
            let body: String = lines.collect::<Vec<_>>().join("\n");
            if let Some(ct) = content_type {
                let base = ct.split(';').next().unwrap_or_default().trim().to_ascii_lowercase();
                assert!(
                    base != "*/*" && !base.ends_with("/*"),
                    "{path} block {idx}: wildcard Content-Type header {ct:?}"
                );
                if base == "application/json" || base.ends_with("+json") {
                    serde_json::from_str::<serde_json::Value>(&body)
                        .unwrap_or_else(|err| panic!("{path} block {idx}: invalid JSON body: {err}\n{body}"));
                } else if base == "multipart/form-data" {
                    let boundary = ct
                        .split(';')
                        .skip(1)
                        .find_map(|p| {
                            let (k, v) = p.split_once('=')?;
                            k.trim().eq_ignore_ascii_case("boundary").then(|| v.trim())
                        })
                        .unwrap_or_else(|| panic!("{path} block {idx}: multipart header missing boundary: {ct}"));
                    let open = format!("--{boundary}");
                    let close = format!("--{boundary}--");
                    assert!(
                        body.starts_with(&format!("{open}\n")),
                        "{path} block {idx}: multipart body does not start with {open}"
                    );
                    assert!(
                        body.ends_with(&close),
                        "{path} block {idx}: multipart body does not end with {close}"
                    );
                    let inner = body
                        .strip_prefix(&format!("{open}\n"))
                        .and_then(|s| s.strip_suffix(&close))
                        .unwrap();
                    for part in inner.split(&format!("\n{open}\n")) {
                        let (part_headers, part_body) = part
                            .split_once("\n\n")
                            .unwrap_or_else(|| panic!("{path} block {idx}: malformed multipart part:\n{part}"));
                        assert!(
                            part_headers.contains("Content-Disposition: form-data;"),
                            "{path} block {idx}: missing Content-Disposition:\n{part_headers}"
                        );
                        if part_headers.contains("Content-Type: application/json") {
                            serde_json::from_str::<serde_json::Value>(part_body.trim()).unwrap_or_else(|err| {
                                panic!("{path} block {idx}: invalid JSON multipart part: {err}\n{part_body}")
                            });
                        }
                    }
                }
            }
        }
    }

    const OK_JSON: &str = r#""responses": {"200": {
      "description": "ok",
      "content": {"application/json": {"schema": {"type": "object", "properties": {"id": {"type": "string"}}}}}
    }}"#;

    #[test]
    fn layout_groups_as_folders_endpoints_as_files() {
        let forge = build_paths(&format!(
            r#"{{
              "/health": {{
                "get": {{
                  "operationId": "health",
                  "summary": "Check health",
                  "responses": {{"204": {{"description": "ok"}}}}
                }}
              }},
              "/projects": {{
                "get": {{
                  "x-forge-group-name": "projects",
                  "x-forge-method-name": "list",
                  {OK_JSON}
                }}
              }},
              "/projects/{{project_id}}/archive": {{
                "post": {{
                  "x-forge-group-name": "projects",
                  "x-forge-method-name": "archive",
                  {OK_JSON}
                }}
              }},
              "/projects/{{project_id}}/archive/restore": {{
                "post": {{
                  "x-forge-group-name": "projects.archive",
                  "x-forge-method-name": "restore",
                  {OK_JSON}
                }}
              }},
              "/projects/{{project_id}}/members": {{
                "post": {{
                  "x-forge-group-name": "projects.members",
                  "x-forge-method-name": "create",
                  {OK_JSON}
                }}
              }},
              "/internal": {{
                "get": {{
                  "x-forge-group-name": "projects",
                  "x-forge-method-name": "skipped",
                  "x-forge-skip": true,
                  {OK_JSON}
                }}
              }}
            }}"#
        ));

        let files = generate(&forge);
        assert_eq!(
            files.keys().collect::<Vec<_>>(),
            [
                "README.md",
                "health.http",
                "projects/archive.http",
                "projects/archive/restore.http",
                "projects/list.http",
                "projects/members/create.http",
            ]
        );
        assert!(files["health.http"].contains("# @name health\nGET {{baseUrl}}/health\n"));
        assert!(!files["health.http"].contains("Accept:"));
        assert!(files["projects/list.http"].contains("Accept: application/json\n"));
        assert!(files["projects/members/create.http"].contains("@project_id = <project_id>\n"));
        assert!(
            files["projects/members/create.http"]
                .contains("# @name projects_members_create\nPOST {{baseUrl}}/projects/{{project_id}}/members\n")
        );
    }

